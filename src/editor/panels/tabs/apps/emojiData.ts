/**
 * A compact emoji catalogue for the Emoji app: each entry is "<emoji> <name and search words>". Only emoji that
 * every current system font draws are included. Glyphs that need the emoji variation selector are written with
 * escapes (️) so they render in colour.
 */

export interface EmojiCategory {
  id: string;
  label: string;
  /** the emoji shown on the category chip */
  icon: string;
  items: Array<{ char: string; name: string }>;
}

